import textwrap
from typing import List, Dict, Any


def build_document_analysis_prompt(document_text: str, docs: List[Dict[str, Any]]) -> str:
    """Промпт для анализа документа на соответствие законодательству."""
    doc_preview = document_text.strip()
    if len(doc_preview) > 8000:
        doc_preview = doc_preview[:8000] + "\n\n[Документ обрезан по длине для анализа]"

    context_chunks = []
    for i, point in enumerate(docs, start=1):
        payload = point.get("payload", {}) or {}
        text = payload.get("text", "")
        source = payload.get("source", "неизвестный файл")

        short_text = textwrap.shorten(
            text,
            width=1200,
            placeholder=" ...",
        )

        context_chunks.append(
            f"[{i}] Источник: {source}\n"
            f"Фрагмент:\n{short_text}\n"
        )

    legal_context = "\n\n".join(context_chunks)

    prompt = f"""
Ты — ИИ-юрист по российскому праву.

Тебе переданы:
1) Текст документа клиента (например, договор, политика, положение).
2) Выдержки из нормативных правовых актов Российской Федерации, потенциально относящиеся к этому документу.

Твоя задача — оценить, насколько документ соответствует приведённым нормам.

Уровни оценки:
- GREEN (Зелёный) — существенных нарушений не видно, документ в целом соответствует требованиям, возможны только мелкие уточнения.
- YELLOW (Жёлтый) — есть риски и вопросы к соответствию, желательно доработка и консультация с юристом.
- RED (Красный) — очевидные и/или серьёзные несоответствия, высокий риск нарушений, документ нельзя использовать без серьёзной переработки.

ВАЖНО:
- Оценивай только на основе ТЕКСТА ДОКУМЕНТА и ПРИВЕДЁННЫХ НОРМ.
- Если информации явно недостаточно, склоняйся к Жёлтому или Красному и указывай, чего именно не хватает.
- Это предварительное заключение ИИ, не заменяющее юридическую экспертизу человека.

Текст документа клиента:
\"\"\"text
{doc_preview}
\"\"\"


Фрагменты нормативных актов:
{legal_context}

Ответь СТРОГО одним JSON-объектом БЕЗ текста вне JSON, в формате:

{{
  "grade": "GREEN" | "YELLOW" | "RED",
  "grade_label_ru": "Зелёный" | "Жёлтый" | "Красный",
  "explanation": "Краткое резюме оценки (на русском, 3–7 предложений).",
  "recommendations": "Конкретные рекомендации, что доработать в документе (на русском)."
}}

Не добавляй никаких комментариев до или после JSON.
"""
    return textwrap.dedent(prompt).strip()
