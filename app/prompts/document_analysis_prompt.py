import textwrap
from typing import List, Dict, Any


def build_document_analysis_prompt(document_text: str, docs: List[Dict[str, Any]]) -> str:
    """
    Промпт: оценка договора по 10 фиксированным осям.
    Документ — основной источник, НПА (docs) — нормативный контекст.
    """
    doc_preview = document_text.strip()
    if len(doc_preview) > 8000:
        doc_preview = doc_preview[:8000] + "\n\n[Документ обрезан по длине для анализа]"

    context_chunks = []
    for i, point in enumerate(docs, start=1):
        payload = point.get("payload", {}) or {}
        text = payload.get("text", "")
        source = payload.get("source", "неизвестный файл")

        short_text = textwrap.shorten(text, width=1200, placeholder=" ...")

        context_chunks.append(
            f"[{i}] Источник: {source}\n"
            f"Фрагмент:\n{short_text}\n"
        )

    legal_context = "\n\n".join(context_chunks)

    prompt = f"""
Ты — ИИ-юрист по российскому праву.

Тебе переданы:
1) Текст договора клиента (поставка, услуги и т.п.).
2) Выдержки из нормативных правовых актов РФ, относящихся к договору.

Главное:
- Анализируй **прежде всего текст договора**.
- Фрагменты НПА используй как нормативный контекст: чтобы понять, какие требования предъявляет закон и что будет «здравым смыслом» для юриста.
- Не придумывай нормы, опирайся на переданные фрагменты НПА. Если в НПА что-то не описано — не делай жёстких утверждений.

Нужно оценить договор по 10 фиксированным осям (каждая — максимум 10 баллов):

1. {{
  "code": "parties",
  "title": "Идентификация сторон, полномочия, реквизиты",
  "max_score": 10
}}
2. {{
  "code": "subject",
  "title": "Предмет/результат, измеримость (SOW/ТЗ)",
  "max_score": 10
}}
3. {{
  "code": "timeline_acceptance",
  "title": "Сроки, поставка/оказание, приемка, milestones",
  "max_score": 10
}}
4. {{
  "code": "price_payment",
  "title": "Цена, налоги, порядок платежей, удержания",
  "max_score": 10
}}
5. {{
  "code": "liability",
  "title": "Ответственность, неустойки/штрафы, лимиты (cap)",
  "max_score": 10
}}
6. {{
  "code": "warranties",
  "title": "Гарантии и заверения сторон",
  "max_score": 10
}}
7. {{
  "code": "force_majeure",
  "title": "Форс-мажор",
  "max_score": 10
}}
8. {{
  "code": "termination",
  "title": "Изменение/расторжение, односторонний отказ",
  "max_score": 10
}}
9. {{
  "code": "governing_law",
  "title": "Применимое право и подсудность/арбитраж",
  "max_score": 10
}}
10. {{
  "code": "documents_priority",
  "title": "Конфликты/приоритет документов, приложения",
  "max_score": 10
}}

Важные уточнения:
- Эти секции НЕ обязаны быть отдельными разделами договора. Это **вопросы**, на которые нужно найти ответы в тексте.
- Для каждой оси ищи в документе всё, что к ней относится (даже если это размазано по разным пунктам).
- Оценивай:
  - насколько тема вообще покрыта (есть/нет, сколько деталей),
  - есть ли явные расхождения с нормами права (по переданным НПА),
  - насколько формулировки логичны и практичны для сторон.
- Ставь балл от 0 до 10:
  - 0–3: тема почти не раскрыта или есть опасные формулировки.
  - 4–6: тема раскрыта частично, есть пробелы/риски.
  - 7–8: в целом всё нормально, мелкие вопросы.
  - 9–10: хорошо проработанный раздел, без явных проблем.
- НЕ выставляй ***общую*** оценку договора и не считай суммарный балл — этим займётся сервис.

Структура отчёта, которую нужно вернуть:

1) "summary"
   Текст, который содержит ДВЕ части:
   - краткое содержание договора: кто с кем в общих чертах и каков основной предмет договора;
   - экспертную оценку документа: общее впечатление юриста о качестве и рисках документа.
   Всё в одном текстовом поле (1–3 абзаца, по-русски).

2) "sections"
   Ровно 10 элементов — по одному на каждую ось выше.
   Для каждой секции:
   - "code" — один из: parties, subject, timeline_acceptance, price_payment, liability, warranties, force_majeure, termination, governing_law, documents_priority;
   - "title" — понятное название секции (можно использовать формулировки выше);
   - "score" — число от 0 до 10 (оценка по этой теме);
   - "comment" — короткий комментарий по этому вопросу: что хорошо/плохо, чего не хватает.

3) "key_risks"
   Список секций, по которым самые серьёзные вопросы, в порядке важности.
   Каждый элемент:
   - "section_code" — код секции;
   - "title" — её название;
   - "issue" — кратко, в чём проблема по этому вопросу;
   - "recommendation" — что лучше изменить/дописать.

4) "recommendations"
   Общий текст "Замечания и рекомендации": 2–8 предложений с резюме основных доработок по договору.

Текст договора:
\"\"\"text
{doc_preview}
\"\"\"


Фрагменты нормативных актов (контекст для оценки, не переписывай их дословно):
{legal_context}

Ответь СТРОГО одним JSON-объектом БЕЗ текста вне JSON, в формате:

{{
  "summary": "…",
  "recommendations": "…",
  "sections": [
    {{
      "code": "parties",
      "title": "Идентификация сторон, полномочия, реквизиты",
      "score": <0-10>,
      "comment": "…"
    }},
    ...
  ],
  "key_risks": [
    {{
      "section_code": "price_payment",
      "title": "Цена, налоги, порядок платежей, удержания",
      "issue": "…",
      "recommendation": "…"
    }},
    ...
  ]
}}

Не добавляй никаких комментариев до или после JSON.
"""
    return textwrap.dedent(prompt).strip()
